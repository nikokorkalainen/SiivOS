"""Writes SiivOSWordmark.swift: the name "SiivOS" in Nunito ExtraBold as SwiftUI paths.

Usage: python3 -I make_wordmark.py <nunito-variable.ttf> <output.swift>
"""
import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

FONT_PATH, OUT = Path(sys.argv[1]), Path(sys.argv[2])


def num(v: float) -> str:
    text = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


class SwiftPen(BasePen):
    """Records outlines as Swift `Path` calls."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.lines = []

    def _pt(self, p):
        return f"CGPoint(x: {num(p[0])}, y: {num(p[1])})"

    def _moveTo(self, p):
        self.lines.append(f"path.move(to: {self._pt(p)})")

    def _lineTo(self, p):
        self.lines.append(f"path.addLine(to: {self._pt(p)})")

    def _qCurveToOne(self, p1, p2):
        self.lines.append(f"path.addQuadCurve(to: {self._pt(p2)}, control: {self._pt(p1)})")

    def _curveToOne(self, p1, p2, p3):
        self.lines.append(f"path.addCurve(to: {self._pt(p3)}, control1: {self._pt(p1)}, control2: {self._pt(p2)})")

    def _closePath(self):
        self.lines.append("path.closeSubpath()")


def main() -> None:
    font = instantiateVariableFont(TTFont(FONT_PATH), {"wght": 800})
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = 100 / font["head"].unitsPerEm  # 100 units per em

    letters, x = [], 0
    for ch in "SiivOS":
        name = cmap[ord(ch)]
        letters.append((name, x))
        x += font["hmtx"][name][0]

    bounds = BoundsPen(glyph_set)
    for name, gx in letters:
        glyph_set[name].draw(TransformPen(bounds, (1, 0, 0, 1, gx, 0)))
    x_min, y_min, x_max, y_max = bounds.bounds
    width = (x_max - x_min) * scale
    height = (y_max - y_min) * scale

    groups = {"siiv": letters[:4], "os": letters[4:]}
    bodies = {}
    for key, group in groups.items():
        pen = SwiftPen(glyph_set)
        for name, gx in group:
            # Font units are y-up: flip, and move the ink box to (0, 0).
            t = (scale, 0, 0, -scale, (gx - x_min) * scale, y_max * scale)
            glyph_set[name].draw(TransformPen(pen, t))
        bodies[key] = "\n".join("        " + line for line in pen.lines)

    OUT.write_text(f'''import AppKit
import SwiftUI

// Generated by design/icon/make_wordmark.py from Nunito ExtraBold (SIL Open Font License).
// Edit the script, not this file.

/// The name "SiivOS" as drawn in the logo: Nunito ExtraBold, with "OS" in the accent green.
/// Drawn from outlines, so it needs no font installed.
///
///     SiivOSWordmark().frame(height: 16)
struct SiivOSWordmark: View {{
    var body: some View {{
        Canvas {{ graphics, canvasSize in
            let scale = min(canvasSize.width / SiivOSWordmarkPaths.size.width, canvasSize.height / SiivOSWordmarkPaths.size.height)
            graphics.scaleBy(x: scale, y: scale)
            graphics.fill(SiivOSWordmarkPaths.siiv, with: .color(SiivOSWordmarkPaths.siivColor))
            graphics.fill(SiivOSWordmarkPaths.os, with: .color(SiivOSWordmarkPaths.osColor))
        }}
        .aspectRatio(SiivOSWordmarkPaths.size.width / SiivOSWordmarkPaths.size.height, contentMode: .fit)
        .accessibilityElement()
        .accessibilityLabel("SiivOS")
    }}
}}

enum SiivOSWordmarkPaths {{
    /// The ink box of the name, in units where one em is 100.
    static let size = CGSize(width: {num(width)}, height: {num(height)})

    /// "Siiv": soft white (#F1F7F3) in dark mode, deep green (#0B3D30) in light mode.
    static let siivColor = adaptive(
        dark: NSColor(srgbRed: 0.945, green: 0.969, blue: 0.953, alpha: 1),
        light: NSColor(srgbRed: 0.043, green: 0.239, blue: 0.188, alpha: 1)
    )

    /// "OS": mint (#5EE6A8) in dark mode, jade (#178A64) in light mode.
    static let osColor = adaptive(
        dark: NSColor(srgbRed: 0.369, green: 0.902, blue: 0.659, alpha: 1),
        light: NSColor(srgbRed: 0.090, green: 0.541, blue: 0.392, alpha: 1)
    )

    static let siiv: Path = {{
        var path = Path()
{bodies["siiv"]}
        return path
    }}()

    static let os: Path = {{
        var path = Path()
{bodies["os"]}
        return path
    }}()

    private static func adaptive(dark: NSColor, light: NSColor) -> Color {{
        Color(nsColor: NSColor(name: nil) {{ appearance in
            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
        }})
    }}
}}
''')
    print(f"wrote {OUT} ({num(width)} x {num(height)})")


if __name__ == "__main__":
    main()
