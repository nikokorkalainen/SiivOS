"""Writes Sources/SiivOS/SiivOSWordmark.swift from the master logo file.

The logo (design/logo/SiivOS-logo-for-light-backgrounds.svg) is turned into SwiftUI paths, so the
app draws exactly the owner's artwork with no font or image files. Edit the logo, then run:

    python3 design/icon/make_wordmark.py

Needs Python with fontTools (for its SVG path reader).
"""
import re
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parents[2]
LOGO = ROOT / "design" / "logo" / "SiivOS-logo-for-light-backgrounds.svg"
OUT = ROOT / "Sources" / "SiivOS" / "SiivOSWordmark.swift"


def num(v: float) -> str:
    text = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


class SwiftPen(BasePen):
    """Records outlines as Swift `Path` calls, moved by (dx, dy)."""

    def __init__(self, dx=0.0, dy=0.0):
        super().__init__(None)
        self.dx, self.dy = dx, dy
        self.lines = []

    def _pt(self, p):
        return f"CGPoint(x: {num(p[0] + self.dx)}, y: {num(p[1] + self.dy)})"

    def _moveTo(self, p):
        self.lines.append(f"path.move(to: {self._pt(p)})")

    def _lineTo(self, p):
        self.lines.append(f"path.addLine(to: {self._pt(p)})")

    def _qCurveToOne(self, p1, p2):
        self.lines.append(f"path.addQuadCurve(to: {self._pt(p2)}, control: {self._pt(p1)})")

    def _curveToOne(self, p1, p2, p3):
        self.lines.append(f"path.addCurve(to: {self._pt(p3)}, control1: {self._pt(p1)}, control2: {self._pt(p2)})")

    def _closePath(self):
        self.lines.append("path.closeSubpath()")


def swift_body(paths, dx=0.0, dy=0.0) -> str:
    pen = SwiftPen(dx, dy)
    for d in paths:
        parse_path(d, pen)
    return "\n".join("        " + line for line in pen.lines)


def subpaths(d: str) -> list:
    """The closed outlines a shape is made of, each as a path of its own.

    Every outline after the first has to start with an absolute move, or it could not be
    drawn on its own.
    """
    parts = [part.strip() for part in re.split(r"(?<=[Zz])", d) if part.strip()]
    assert all(part.startswith("M") for part in parts), "an outline starts with a relative move"
    return parts


def swift_path(paths, indent: str) -> str:
    """A Swift expression that builds one `Path` from the given outlines."""
    pen = SwiftPen()
    for d in paths:
        parse_path(d, pen)
    body = "\n".join(indent + "    " + line for line in pen.lines)
    # The closure says what it returns, so that Swift need not work it out for every
    # entry of a long list.
    return f"{{ () -> Path in\n{indent}    var path = Path()\n{body}\n{indent}    return path\n{indent}}}()"


def swift_list(items, indent: str) -> str:
    return "[\n" + ",\n".join(indent + "    " + item for item in items) + f"\n{indent}]"


def center(d: str) -> str:
    bounds = BoundsPen(None)
    parse_path(d, bounds)
    x0, y0, x1, y1 = bounds.bounds
    return f"CGPoint(x: {num((x0 + x1) / 2)}, y: {num((y0 + y1) / 2)})"


def main() -> None:
    svg = LOGO.read_text()
    width, height = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()[2:]]
    shapes = re.findall(r'<path class="(st\d)" d="([^"]+)"', svg)
    letters, glints = shapes[:-2], shapes[-2:]

    # The name alone: its ink box, so it can be drawn without the glints.
    bounds = BoundsPen(None)
    for _, d in letters:
        parse_path(d, bounds)
    x0, y0, x1, y1 = bounds.bounds

    # The logo taken apart, for the welcome's animation: each glint, and each character of
    # the name. The file draws "OS" as one shape, so that one is split into the O (its
    # outer and inner edge) and the S.
    (_, big_glint), (_, small_glint) = glints
    plain = [d for _, d in letters]
    assert len(plain) == 7, "expected S, i, dot, i, dot, v and OS"
    o_outer, o_inner, last_s = subpaths(plain[6])
    characters = [
        [plain[0]],            # S
        [plain[1], plain[2]],  # i with its dot
        [plain[3], plain[4]],  # i with its dot
        [plain[5]],            # v
        [o_outer, o_inner],    # O
        [last_s],              # S
    ]
    letters_swift = swift_list([swift_path(parts, "        ") for parts in characters], "    ")
    outlines_swift = swift_list(
        [swift_list([swift_path([part], "            ") for part in parts], "        ") for parts in characters],
        "    ",
    )

    logo_dark = swift_body([d for c, d in shapes if c == "st0"])
    logo_light = swift_body([d for c, d in shapes if c == "st1"])
    name_dark = swift_body([d for c, d in letters if c == "st0"], -x0, -y0)
    name_light = swift_body([d for c, d in letters if c == "st1"], -x0, -y0)

    OUT.write_text(f'''import AppKit
import SwiftUI

// Generated by design/icon/make_wordmark.py from design/logo/SiivOS-logo-for-light-backgrounds.svg.
// Edit the logo file and run the script; do not edit this file by hand.

/// The SiivOS logo for the app's interface: the name with the two glints off the top-left of the
/// S, exactly as in the logo file. "Siiv" and the big glint share one colour, "OS" and the small
/// glint the other.
///
///     SiivOSLogo().frame(height: 39)
struct SiivOSLogo: View {{
    var body: some View {{
        Canvas {{ graphics, canvasSize in
            let box = SiivOSLogoPaths.logoSize
            let scale = min(canvasSize.width / box.width, canvasSize.height / box.height)
            graphics.scaleBy(x: scale, y: scale)
            graphics.fill(SiivOSLogoPaths.logoSiiv, with: .color(SiivOSLogoPaths.siivColor))
            graphics.fill(SiivOSLogoPaths.logoOS, with: .color(SiivOSLogoPaths.osColor))
        }}
        .aspectRatio(SiivOSLogoPaths.logoSize.width / SiivOSLogoPaths.logoSize.height, contentMode: .fit)
        .accessibilityElement()
        .accessibilityLabel("SiivOS")
    }}
}}

/// The name "SiivOS" alone, without the glints, with the logo's letter spacing.
///
///     SiivOSWordmark().frame(height: 16)
struct SiivOSWordmark: View {{
    var body: some View {{
        Canvas {{ graphics, canvasSize in
            let box = SiivOSLogoPaths.nameSize
            let scale = min(canvasSize.width / box.width, canvasSize.height / box.height)
            graphics.scaleBy(x: scale, y: scale)
            graphics.fill(SiivOSLogoPaths.nameSiiv, with: .color(SiivOSLogoPaths.siivColor))
            graphics.fill(SiivOSLogoPaths.nameOS, with: .color(SiivOSLogoPaths.osColor))
        }}
        .aspectRatio(SiivOSLogoPaths.nameSize.width / SiivOSLogoPaths.nameSize.height, contentMode: .fit)
        .accessibilityElement()
        .accessibilityLabel("SiivOS")
    }}
}}

enum SiivOSLogoPaths {{
    /// The logo file's canvas.
    static let logoSize = CGSize(width: {num(width)}, height: {num(height)})

    /// The ink box of the name alone.
    static let nameSize = CGSize(width: {num(x1 - x0)}, height: {num(y1 - y0)})

    /// "Siiv" and the big glint: soft white (#F1F7F3) in dark mode, deep green (#0B3D30) in light mode.
    static let siivColor = adaptive(
        dark: NSColor(srgbRed: 0.945, green: 0.969, blue: 0.953, alpha: 1),
        light: NSColor(srgbRed: 0.043, green: 0.239, blue: 0.188, alpha: 1)
    )

    /// "OS" and the small glint: mint (#5EE6A8) in dark mode, jade (#178A64) in light mode.
    static let osColor = adaptive(
        dark: NSColor(srgbRed: 0.369, green: 0.902, blue: 0.659, alpha: 1),
        light: NSColor(srgbRed: 0.090, green: 0.541, blue: 0.392, alpha: 1)
    )

    static let logoSiiv: Path = {{
        var path = Path()
{logo_dark}
        return path
    }}()

    static let logoOS: Path = {{
        var path = Path()
{logo_light}
        return path
    }}()

    static let nameSiiv: Path = {{
        var path = Path()
{name_dark}
        return path
    }}()

    static let nameOS: Path = {{
        var path = Path()
{name_light}
        return path
    }}()

    // The logo taken apart, in the logo file's own coordinates, for the welcome's animation.

    /// The big glint alone. It takes the colour of "Siiv".
    static let logoBigGlint: Path = {swift_path([big_glint], "    ")}

    /// The small glint alone. It takes the colour of "OS".
    static let logoSmallGlint: Path = {swift_path([small_glint], "    ")}

    /// The middle of each glint, which it turns and grows around.
    static let logoBigGlintCenter = {center(big_glint)}
    static let logoSmallGlintCenter = {center(small_glint)}

    /// The ink box of the name where it sits in the logo.
    static let logoNameBox = CGRect(x: {num(x0)}, y: {num(y0)}, width: {num(x1 - x0)}, height: {num(y1 - y0)})

    /// How many of the characters are "Siiv". The rest are "OS".
    static let logoSiivCount = 4

    /// The characters of the name, each as one shape to fill: S, i, i, v, O, S. Each i has
    /// its dot, and the O its hole.
    static let logoLetters: [Path] = {letters_swift}

    /// The same characters as the closed outlines they are made of, so that each outline
    /// can be traced on its own: the stem and the dot of an i, the outer and inner edge of
    /// the O.
    static let logoLetterOutlines: [[Path]] = {outlines_swift}

    private static func adaptive(dark: NSColor, light: NSColor) -> Color {{
        Color(nsColor: NSColor(name: nil) {{ appearance in
            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
        }})
    }}
}}
''')
    print(f"wrote {OUT}: logo {num(width)} x {num(height)}, name {num(x1 - x0)} x {num(y1 - y0)}")


if __name__ == "__main__":
    main()
